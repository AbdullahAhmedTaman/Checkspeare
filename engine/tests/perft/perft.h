#pragma once

#include "board/position.h"
#include <cstdint>

/**
 * @file perft.h
 * @brief Performance Test (Perft) interface for verifying move generation correctness
 *        and position state transitions (make_move / unmake_move).
 */
namespace Perft
{

    /**
     * @brief Recursively counts all leaf nodes at a given target depth.
     *
     * Walks the move tree up to 'depth' plies. Useful for internal benchmarking
     * and recursive move generation verification.
     *
     * @param pos The current board position.
     * @param depth Remaining search depth in plies.
     * @return uint64_t Total number of leaf nodes reached at the specified depth.
     */
    Key run(Position& pos, int depth);

    /**
     * @brief Runs Perft from the root position and prints a detailed breakdown.
     *
     * Iterates through all legal moves in the root position, counts the subtree nodes
     * generated by each move, prints the per-move move count, and displays the total
     * leaf nodes along with execution time.
     *
     * @param pos The root board position to test.
     * @param depth The target search depth in plies.
     */
    void divide(Position& pos, int depth);
} // namespace Perft
